const SORTED_TRANSLATIONS = Object.entries(ENGLISH).sort((a, b) => b[0].length - a[0].length);

const getOriginal = (node) => {
  if (!textNodes.has(node)) textNodes.set(node, node.nodeValue);
  return textNodes.get(node);
};

export function getLanguage() {
  if (activeLanguage) return activeLanguage;
  try { return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'hi'; }
  catch { return 'hi'; }
}

export function translateText(value, language = getLanguage()) {
  if (language !== 'en' || !value) return value;
  const exact = ENGLISH[value.trim()];
  if (exact) return value.replace(value.trim(), exact);
  let translated = value;
  for (const [hi, en] of SORTED_TRANSLATIONS) {
    if (hi.length < 6 || !translated.includes(hi)) continue;
    translated = translated.split(hi).join(en);
  }
  return translated;
}

function translateNode(node, language) {
  const original = getOriginal(node);
  const englishValue = node.parentElement && node.parentElement.closest('[data-i18n-en]')?.getAttribute('data-i18n-en');
  node.nodeValue = language === 'en' && englishValue ? englishValue : translateText(original, language);
}

function translateElement(element, language) {
  let originals = attributes.get(element);
  if (!originals) { originals = new Map(); attributes.set(element, originals); }
  const names = ['aria-label', 'data-l', 'placeholder', 'title', 'alt'];
  if (element.tagName === 'META' && (element.name === 'description' || ['og:title', 'og:description', 'og:locale'].includes(element.getAttribute('property')))) names.push('content');
  for (const name of names) {
    if (!element.hasAttribute(name)) continue;
    if (!originals.has(name)) originals.set(name, element.getAttribute(name));
    element.setAttribute(name, translateText(originals.get(name), language));
  }
}

export function applyLanguage(root = document) {
  const language = getLanguage();
  document.documentElement.lang = language;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let node = root.nodeType === Node.TEXT_NODE ? root : walker.nextNode();
  while (node) {
    if (node.nodeType === Node.TEXT_NODE) {
      if (!node.parentElement.closest('script, style, textarea, [data-no-i18n]')) translateNode(node, language);
    } else translateElement(node, language);
    node = walker.nextNode();
  }
  if (document.title !== translatedTitle) originalTitle = document.title;
  translatedTitle = translateText(originalTitle, language);
  document.title = translatedTitle;
  document.querySelectorAll('[data-language-toggle]').forEach((button) => {
    const label = language === 'en' ? 'हिन्दी' : 'English';
    const ariaLabel = language === 'en' ? 'Switch to Hindi' : 'Switch to English';
    if (button.textContent !== label) button.textContent = label;
    if (button.getAttribute('aria-label') !== ariaLabel) button.setAttribute('aria-label', ariaLabel);
  });
}

export function setLanguage(language) {
  const selected = language === 'en' ? 'en' : 'hi';
  activeLanguage = selected;
  try { localStorage.setItem(STORAGE_KEY, selected); } catch { /* storage is optional */ }
  applyLanguage();
}

export function initLanguage() {
  activeLanguage = getLanguage();
  applyLanguage();
  document.addEventListener('click', (event) => {
    if (!event.target.closest('[data-language-toggle]')) return;
    setLanguage(getLanguage() === 'en' ? 'hi' : 'en');
  });
  observer = new MutationObserver((records) => {
    for (const record of records) {
      for (const node of record.addedNodes) {
        if (node.nodeType === Node.ELEMENT_NODE || node.nodeType === Node.TEXT_NODE) applyLanguage(node);
      }
    }
  });
  observer.observe(document.body, { childList: true, subtree: true });
}
